    '(2)根据能量守恒建立光源角度θ_i到目标位置x_i的映射关系（如等能量映射或等间距映射）；\n'
    '(3)给定初始点P₀（光学面顶点）的坐标和法向量；\n'
    '(4)对i=1,2,...,N：利用折射定律由入射方向s_i（对应θ_i）、出射方向t_i（对应目标点x_i）和上一步的法向量n_{i-1}，求解当前点坐标P_i及其法向量n_i；\n'
    '(5)得到离散点序列{P_i}，经NURBS或样条插值得到光滑曲面轮廓。\n'
    '关键方程形式：dP/dθ=F(P,θ)（一阶ODE系统），可通过标准RK4方法求解。'
